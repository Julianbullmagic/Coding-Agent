  '                if (this.calendarHandler) {',
  '                    return await this.calendarHandler({',
  "                        action: name === 'list_calendar_events' ? 'list' : name === 'create_calendar_event' ? 'create' : name === 'update_calendar_event' ? 'update' : 'delete',",
