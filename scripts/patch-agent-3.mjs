  '    private async provideDeepSeekSuggestions(',
  '        prompt: string,',
  '        apiKey: string,',
  "        history: Array<{ role: 'user' | 'assistant'; content: string }>,",
  '        workspacePath: string,',
  '        maxToolRounds: number,',
